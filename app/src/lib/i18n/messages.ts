export type MessageKey = keyof typeof MESSAGES;

/** Settings whose text can be translated (key in the translations table: "setting.<key>"). */
export const TRANSLATABLE_SETTINGS = [
  "site_tagline",
  "home_hero_title",
  "home_hero_subtitle",
  "footer_text",
  "copyright_text",
  "meta_title",
  "meta_description",
  "cookie_consent_text",
  "maintenance_message",
] as const;

export type TranslatableSetting = (typeof TRANSLATABLE_SETTINGS)[number];

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Splits a message around its placeholders so they can be replaced with rich content (e.g. links or bold text). */
export function interpolateParts<T>(text: string, vars: Record<string, T>): Array<string | T> {
  return text
    .split(/\{(\w+)\}/g)
    .map((part, i) => (i % 2 === 1 ? (part in vars ? vars[part] : `{${part}}`) : part))
    .filter((part) => part !== "");
}

/** Message bases that have a singular ("…One") and a plural ("…Other") variant. */
export type PluralKey = {
  [K in MessageKey]: K extends `${infer Base}One` ? (`${Base}Other` extends MessageKey ? Base : never) : never;
}[MessageKey];

/**
 * Picks the singular or plural variant of a message by count: `{base}One` for 1, `{base}Other` otherwise.
 * `{n}` is filled with the count unless `vars.n` (e.g. a formatted number) is given.
 */
export function plural(t: Translator, base: PluralKey, count: number, vars?: Record<string, string | number>): string {
  return t(`${base}${count === 1 ? "One" : "Other"}` as MessageKey, { n: count, ...vars });
}
